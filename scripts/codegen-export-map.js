/**
 * codegen-export-map.js — generates the do/config -> parameter mapping that ships
 * into every generated project for do/export (Wave 8, BL160 / OQ-8.5 / OQ-8.6).
 *
 * Source of truth: config/parameter-schema-v2.json. Every parameter that carries a
 * `doConfigVar` is a user input persisted in do/config; this script projects the
 * fields do/export needs (schema key, do/config var, type, default, CLI flag, env
 * var, applicable deployment targets / architectures, the literal do/config renders
 * when the parameter is unset, secret flag, value shape) into
 * templates/do/lib/python/export_map.json, which do/lib/python/export_config.py
 * reads at runtime. No hand-maintained table lives in do/export.
 *
 * Output is deterministic (2-space JSON, trailing newline, schema order, no
 * timestamp), so re-running is a no-op. test/unit/do-config-schema-mapping.test.js
 * asserts the checked-in copy equals renderExportMap() (drift test).
 * Run via `npm run codegen`.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

export const SCHEMA_PATH = path.join(ROOT, 'config', 'parameter-schema-v2.json');
export const EXPORT_MAP_PATH = path.join(ROOT, 'templates', 'do', 'lib', 'python', 'export_map.json');

const GENERATED_COMMENT = 'GENERATED by scripts/codegen-export-map.js from ' +
    'config/parameter-schema-v2.json (doConfigVar) - do not edit';

/**
 * Build the export map object from a parsed parameter schema.
 * @param {object} schema - parsed parameter-schema-v2.json
 * @returns {object} the export map
 */
export function buildExportMap(schema) {
    const parameters = [];
    for (const [key, param] of Object.entries(schema.parameters)) {
        if (!param.doConfigVar) continue;
        parameters.push({
            key: param.configKey || key,
            doConfigVar: param.doConfigVar,
            shape: param.doConfigShape || 'scalar',
            type: param.type,
            default: param.default === undefined ? null : param.default,
            cliFlag: param.cliFlag || null,
            envVar: param.envVar || null,
            deploymentTargets: (param.appliesTo && param.appliesTo.deploymentTargets) || ['*'],
            architectures: (param.appliesTo && param.appliesTo.architectures) || ['*'],
            unsetValue: param.doConfigUnsetValue === undefined ? null : param.doConfigUnsetValue,
            sensitive: param.sensitive === true
        });
    }
    return { _generated: GENERATED_COMMENT, parameters };
}

/**
 * Render the export map file content from the on-disk schema.
 * @returns {string}
 */
export function renderExportMap() {
    const schema = JSON.parse(fs.readFileSync(SCHEMA_PATH, 'utf8'));
    return `${JSON.stringify(buildExportMap(schema), null, 2)}\n`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
    const next = renderExportMap();
    const prev = fs.existsSync(EXPORT_MAP_PATH) ? fs.readFileSync(EXPORT_MAP_PATH, 'utf8') : null;
    if (prev !== next) fs.writeFileSync(EXPORT_MAP_PATH, next);
    const count = JSON.parse(next).parameters.length;
    console.log(`✅ Generated templates/do/lib/python/export_map.json (${count} do/config parameters)${prev === next ? ' (unchanged)' : ''}`);
}
