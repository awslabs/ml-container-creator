/**
 * codegen-train-schema.js — generates the SELF-CONTAINED train-manifest schema that
 * ships into every generated project (BL154, OQ-10 option b).
 *
 * Source of truth: config/train-descriptor.schema.json (repo-only). Its knob entries
 * `$ref` the tune descriptor's `$defs/hyperparameter`
 * (templates/code/tune.d/manifest.schema.json) — one knob contract, never copied by
 * hand. A project does not have templates/code/tune.d/ at that relative path, so the
 * shipped copy at templates/do/training/manifest.schema.json INLINES every external
 * `$ref` target under its own `$defs` and rewrites the reference to a local one.
 * Plugin authors can then put `"$schema": "../manifest.schema.json"` in a technique
 * manifest and get editor validation + autocomplete.
 *
 * Output is deterministic (2-space JSON, trailing newline), so re-running is a no-op.
 * test/unit/train-manifest-conformance.test.js asserts the checked-in shipped copy
 * equals renderTrainSchema() (drift test). Run via `npm run codegen`.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

export const SOURCE_SCHEMA = path.join(ROOT, 'config', 'train-descriptor.schema.json');
export const SHIPPED_SCHEMA = path.join(ROOT, 'templates', 'do', 'training', 'manifest.schema.json');

const GENERATED_COMMENT = 'GENERATED by scripts/codegen-train-schema.js from ' +
    'config/train-descriptor.schema.json — do not edit';
const SHIPPED_ID = 'mlcc/training/manifest.schema.json';

/**
 * Resolve a JSON pointer ("/$defs/hyperparameter") inside a parsed document.
 */
function resolvePointer(doc, pointer, where) {
    const parts = pointer.split('/').filter((p) => p !== '')
        .map((p) => p.replace(/~1/g, '/').replace(/~0/g, '~'));
    let node = doc;
    for (const part of parts) {
        if (node === null || typeof node !== 'object' || !(part in node)) {
            throw new Error(`codegen-train-schema: cannot resolve '${pointer}' in ${where}`);
        }
        node = node[part];
    }
    return node;
}

/**
 * Walk `node`, replacing every EXTERNAL `$ref` (one with a file part) with a local
 * `#/$defs/<name>` reference and collecting the inlined definition into `defs`.
 */
function inlineExternalRefs(node, baseDir, defs) {
    if (Array.isArray(node)) {
        return node.map((item) => inlineExternalRefs(item, baseDir, defs));
    }
    if (node === null || typeof node !== 'object') {
        return node;
    }
    const out = {};
    for (const [key, value] of Object.entries(node)) {
        if (key === '$ref' && typeof value === 'string' && !value.startsWith('#')) {
            const [file, pointer = ''] = value.split('#');
            const target = path.resolve(baseDir, file);
            const doc = JSON.parse(fs.readFileSync(target, 'utf8'));
            const def = resolvePointer(doc, pointer, target);
            if (JSON.stringify(def).includes('"$ref"')) {
                // Nested references would need recursive inlining; fail loudly
                // rather than ship a schema with a dangling reference.
                throw new Error(`codegen-train-schema: inlined def '${value}' itself contains a $ref`);
            }
            const name = pointer.split('/').filter((p) => p !== '').pop();
            if (!name) {
                throw new Error(`codegen-train-schema: '${value}' must point at a named definition`);
            }
            defs[name] = def;
            out[key] = `#/$defs/${name}`;
        } else {
            out[key] = inlineExternalRefs(value, baseDir, defs);
        }
    }
    return out;
}

/**
 * Render the shipped, self-contained schema as a string (deterministic).
 */
export function renderTrainSchema() {
    const source = JSON.parse(fs.readFileSync(SOURCE_SCHEMA, 'utf8'));
    const defs = {};
    const body = inlineExternalRefs(source, path.dirname(SOURCE_SCHEMA), defs);
    const shipped = {
        $schema: body.$schema,
        $id: SHIPPED_ID,
        $comment: GENERATED_COMMENT
    };
    for (const [key, value] of Object.entries(body)) {
        if (key === '$schema' || key === '$id' || key === '$comment') continue;
        shipped[key] = value;
    }
    const sortedDefs = {};
    for (const name of Object.keys(defs).sort()) {
        sortedDefs[name] = defs[name];
    }
    shipped.$defs = sortedDefs;
    return `${JSON.stringify(shipped, null, 2)}\n`;
}

function main() {
    const rendered = renderTrainSchema();
    const current = fs.existsSync(SHIPPED_SCHEMA) ? fs.readFileSync(SHIPPED_SCHEMA, 'utf8') : null;
    if (current === rendered) {
        console.log('✓ templates/do/training/manifest.schema.json is up to date');
        return;
    }
    fs.writeFileSync(SHIPPED_SCHEMA, rendered);
    console.log('✓ Wrote templates/do/training/manifest.schema.json');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
    main();
}
