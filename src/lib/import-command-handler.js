/**
 * Import Command Handler
 *
 * Generates an operational project from a running SageMaker endpoint.
 * The generated project has the full operational surface (do/test, do/benchmark,
 * do/adapter, etc.) but no build artifacts (Dockerfile, do/build, do/push).
 *
 * Requirements: US-1 (all ACs)
 */

import { endpointToAnswers } from './endpoint-to-answers.js';
import { writeProject } from '../app.js';
import { fileURLToPath } from 'node:url';
import { resolve, join, dirname } from 'node:path';
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const GENERATOR_ROOT = resolve(__dirname, '../..');
const TEMPLATE_DIR = join(GENERATOR_ROOT, 'templates');

/**
 * Handler for `mcc import <endpoint-arn>`.
 * Reconstructs project configuration from a live SageMaker endpoint.
 */
export default class ImportCommandHandler {
    /**
     * @param {object} options
     * @param {string} [options.outputDir] - Output directory (default: ./<endpoint-name>)
     * @param {boolean} [options.dryRun] - Print what would be generated without writing
     * @param {string} [options.region] - AWS region override
     */
    constructor({ outputDir, dryRun, region } = {}) {
        this.outputDir = outputDir;
        this.dryRun = dryRun || false;
        this.region = region;
    }

    /**
     * Execute the import command.
     * @param {string} endpointArn - Full ARN of the SageMaker endpoint
     */
    async handle(endpointArn) {
        // Parse region from ARN if not provided
        const arnMatch = endpointArn.match(/^arn:aws:sagemaker:([^:]+):/);
        const region = this.region || (arnMatch ? arnMatch[1] : process.env.AWS_DEFAULT_REGION);

        if (!region) {
            console.error('❌ Cannot determine AWS region. Provide --region or set AWS_DEFAULT_REGION.');
            process.exit(1);
        }

        console.log(`\n🔍 Importing endpoint: ${endpointArn}`);
        console.log(`   Region: ${region}`);

        // Call endpointToAnswers
        let answers, icConfs;
        try {
            ({ answers, icConfs } = await endpointToAnswers(endpointArn, region));
        } catch (err) {
            console.error(`\n${err.message}`);
            process.exit(1);
        }

        console.log(`   Status: ${answers.endpointStatus}`);
        console.log(`   Instance: ${answers.instanceType}`);
        console.log(`   Model: ${answers.modelName}`);
        console.log(`   Config: ${answers.deploymentConfig}`);
        console.log(`   ICs: ${icConfs.length}`);

        // Resolve output directory
        const outputDir = this.outputDir || `./${answers.endpointName}`;
        const resolvedOutputDir = resolve(process.cwd(), outputDir);

        if (this.dryRun) {
            console.log('\n📋 Dry run — no files will be written\n');
            console.log('Reconstructed answers:');
            console.log(JSON.stringify(answers, null, 2));
            console.log('\nInference Component configs:');
            console.log(JSON.stringify(icConfs, null, 2));
            console.log(`\nOutput directory: ${resolvedOutputDir}`);
            console.log('\nFiles that would be generated:');
            console.log('  do/config, do/test, do/benchmark, do/deploy, do/clean,');
            console.log('  do/logs, do/status, do/register, do/optimize, do/run');
            for (const ic of icConfs) {
                console.log(`  do/ic/${ic.name}.conf`);
            }
            return;
        }

        // Create output directory
        mkdirSync(resolvedOutputDir, { recursive: true });

        // Write project (skip build artifacts and templates not needed for imported projects)
        const skipTemplates = [
            'Dockerfile', 'do/build', 'do/push', 'do/submit',
            'buildspec.yml', '.dockerignore', 'code/**',
            'deploy_notebook_generator.py', 'IAM_PERMISSIONS.md',
            'PROJECT_README.md', 'requirements.txt',
            'do/export', 'do/validate'
        ];

        await writeProject(TEMPLATE_DIR, resolvedOutputDir, answers, null, {}, null, {
            skipTemplates,
            noGenerationParams: true
        });

        // Write IC conf files
        const icDir = join(resolvedOutputDir, 'do', 'ic');
        mkdirSync(icDir, { recursive: true });

        for (const ic of icConfs) {
            const lines = ['# Generated by mcc import'];
            lines.push(`export IC_GPU_COUNT="${ic.IC_GPU_COUNT}"`);
            lines.push(`export IC_CPU_COUNT="${ic.IC_CPU_COUNT}"`);
            lines.push(`export IC_MEMORY_SIZE="${ic.IC_MEMORY_SIZE}"`);

            // Write all IC_ENV_* variables
            for (const [key, value] of Object.entries(ic)) {
                if (key.startsWith('IC_ENV_')) {
                    lines.push(`export ${key}="${value}"`);
                }
            }

            const confPath = join(icDir, `${ic.name}.conf`);
            writeFileSync(confPath, `${lines.join('\n')  }\n`);
        }

        // Write .mlcc-import-source
        let generatorVersion = '0.0.0';
        try {
            const pkg = JSON.parse(readFileSync(join(GENERATOR_ROOT, 'package.json'), 'utf8'));
            generatorVersion = pkg.version || '0.0.0';
        } catch {
            // Fallback
        }

        const importSource = {
            sourceEndpointArn: endpointArn,
            importedAt: new Date().toISOString(),
            generatorVersion,
            importMode: 'endpoint'
        };

        writeFileSync(
            join(resolvedOutputDir, '.mlcc-import-source'),
            `${JSON.stringify(importSource, null, 2)  }\n`
        );

        // Success message
        console.log('\n✅ Project imported successfully!');
        console.log(`   📁 ${resolvedOutputDir}`);
        console.log('\n   Next steps:');
        console.log(`   cd ${outputDir}`);
        console.log('   ./do/test        # Test the endpoint');
        console.log('   ./do/benchmark   # Run benchmarks');
        console.log('   ./do/status      # Check endpoint status');
        console.log('   ./do/logs        # View CloudWatch logs');
    }
}
