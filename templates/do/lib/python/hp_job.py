class RenderError(Exception):
    """A render refusal (exit 3)."""


class UsageError(Exception):
    """Bad input (exit 2)."""


# ── CLI plumbing ───────────────────────────────────────────────────────────────


def _run(cmd: list[str], timeout: int = 120, stdin: str | None = None) -> tuple[int, str, str]:
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, check=False, input=stdin)
    except FileNotFoundError as exc:
        return 127, "", str(exc)
    except subprocess.TimeoutExpired:
        return 124, "", f"timed out after {timeout}s: {' '.join(cmd[:4])}"
    return p.returncode, p.stdout or "", p.stderr or ""


def _aws(args: list[str], timeout: int = 120) -> tuple[int, str, str]:
    cmd = ["aws", *args]
    if os.environ.get("AWS_REGION"):
        cmd += ["--region", os.environ["AWS_REGION"]]
    return _run(cmd, timeout)


def _json(text: str):
    try:
        return json.loads(text or "")
    except ValueError:
        return None


def _note(msg: str) -> None:
    print(msg, file=sys.stderr)


def _split_s3(uri: str) -> tuple[str, str]:
    rest = uri[len("s3://"):] if uri.startswith("s3://") else uri
    bucket, _, key = rest.partition("/")
    return bucket, key


# ── inputs ─────────────────────────────────────────────────────────────────────


def validate_scratch_size(value: str) -> int:
    """`--scratch-size` is `<N>Gi`, 1..2000 (design §8). Returns N."""
    if not SCRATCH_SIZE_RE.match(value or ""):
        raise UsageError(f"--scratch-size must look like 120Gi (got '{value}')")
    n = int(value[:-2])
    if n > MAX_SCRATCH_GIB:
        raise UsageError(f"--scratch-size {value} exceeds {MAX_SCRATCH_GIB}Gi")
    return n


def validate_timeout(name: str, value) -> int:
    try:
        n = int(value)
    except (TypeError, ValueError):
        raise UsageError(f"{name} must be an integer number of seconds (got '{value}')") from None
    if n < 0 or n > 86400:
        raise UsageError(f"{name} must be between 0 and 86400 (got {n})")
    return n


def scratch_gib(model_bytes: int | None, override: str = "") -> int:
    """R5.2: max(50 GiB, ceil(2.5 x base-model bytes)) unless --scratch-size."""
    if override:
        return validate_scratch_size(override)
    if model_bytes is None:
        raise RenderError("the scratch size cannot be derived (no staged base model in S3): pass --scratch-size <N>Gi")
    return max(MIN_SCRATCH_GIB, int(math.ceil(2.5 * model_bytes / (1024 ** 3))))


def s3_prefix_bytes(uri: str) -> int | None:
    """Total bytes under an S3 prefix (aws s3api list-objects-v2 paginates)."""
    bucket, key = _split_s3(uri)
    if not bucket:
        return None
    rc, out, _ = _aws(["s3api", "list-objects-v2", "--bucket", bucket, "--prefix", key,
                       "--query", "Contents[].Size", "--output", "json"])
    data = _json(out) if rc == 0 else None
    if not isinstance(data, list) or not data:
        return None
    return sum(int(x) for x in data if isinstance(x, (int, float)))


# ── pod additions (shared by render-train and hp_payload.py) ──────────────────


def labels(project: str, kind: str, technique: str, job: str) -> dict:
    return {LABEL_PROJECT: project, LABEL_KIND: kind, LABEL_TECHNIQUE: technique or "custom", LABEL_JOB: job}


def output_prefix(bucket: str, project: str, kind: str, job: str) -> str:
    return f"s3://{bucket}/{project}/{kind}/{job}/"


def scratch_volume(mode: str, project: str, job: str, size_gib: int | None, storage_class: str,
                   lbl: dict) -> tuple[dict, dict]:
    if mode == "fsx":
        vol = {"name": "mlcc-scratch", "persistentVolumeClaim": {"claimName": FSX_CLAIM}}
        mount = {"name": "mlcc-scratch", "mountPath": SCRATCH, "subPath": f"mlcc/{project}/{job}"}
        return vol, mount
    if mode != "ephemeral":
        raise RenderError(f"unknown scratch mode '{mode}' (fsx|ephemeral)")
    if not storage_class or not size_gib:
        raise RenderError("an ephemeral scratch volume needs a StorageClass and a size")
    vol = {"name": "mlcc-scratch", "ephemeral": {"volumeClaimTemplate": {
        "metadata": {"labels": dict(lbl)},
        "spec": {"accessModes": ["ReadWriteOnce"], "storageClassName": storage_class,
                 "resources": {"requests": {"storage": f"{size_gib}Gi"}}}}}}
    return vol, {"name": "mlcc-scratch", "mountPath": SCRATCH}


def _copy_cmd(uri: str, dest: str) -> str:
    # A trailing slash is a prefix (sync); anything else is one object (cp).
    if uri.endswith("/"):
        return f"aws s3 sync --only-show-errors '{uri}' '{dest}/'"
    return f"aws s3 cp --only-show-errors '{uri}' '{dest}/'"


def fetch_container(dataset: str, model_uri: str, region: str, mount: dict) -> dict:
    steps = ["set -eu", f"mkdir -p {SCRATCH}/data {SCRATCH}/model {SCRATCH}/logs {SCRATCH}/output"]
    if dataset.startswith("s3://"):
        steps.append(f"echo 'MLCC fetch: dataset {dataset}'")
        steps.append(_copy_cmd(dataset, f"{SCRATCH}/data"))
    if model_uri.startswith("s3://"):
        steps.append(f"echo 'MLCC fetch: model {model_uri}'")
        steps.append(_copy_cmd(model_uri.rstrip("/") + "/", f"{SCRATCH}/model"))
    steps.append("echo 'MLCC fetch: done'")
    return {"name": "mlcc-fetch", "image": AWS_CLI_IMAGE, "command": ["/bin/sh", "-c", "\n".join(steps)],
            "env": _region_env(region), "volumeMounts": [dict(mount)]}


def egress_container(dest: str, job: str, region: str, mount: dict, clear_scratch: bool) -> dict:
    # Keep the .mlcc-* markers so a container restart never re-runs the workload.
    clear = (f"  find {SCRATCH} -mindepth 1 -maxdepth 1 ! -name '.mlcc-*' -exec rm -rf {{}} + 2>/dev/null || true\n"
             if clear_scratch else "")
    script = (
        "set -u\n"
        f"while [ ! -f {SCRATCH}/.mlcc-exit ]; do sleep 10; done\n"
        f"if [ -f {SCRATCH}/.mlcc-egress-done ]; then while :; do sleep 3600; done; fi\n"
        f"rc=$(cat {SCRATCH}/.mlcc-exit)\n"
        "up=0\n"
        f"echo \"MLCC egress: workload exit $rc; uploading to {dest}\"\n"
        f"aws s3 sync --only-show-errors {SCRATCH}/logs '{dest}logs/' || up=1\n"
        "if [ \"$rc\" = 0 ]; then\n"
        f"  aws s3 sync --only-show-errors {SCRATCH}/output '{dest}output/' || up=1\n"
        "fi\n"
        "if [ \"$up\" = 0 ]; then\n"
        f"  files=$(find {SCRATCH}/output -type f 2>/dev/null | wc -l | tr -d ' ')\n"
        f"  bytes=$(du -sb {SCRATCH}/output 2>/dev/null | cut -f1)\n"
        f"  printf '{{\"job\":\"%s\",\"exit_code\":%s,\"files\":%s,\"bytes\":%s,\"finished\":\"%s\"}}' "
        f"'{job}' \"$rc\" \"${{files:-0}}\" \"${{bytes:-0}}\" \"$(date -u +%Y-%m-%dT%H:%M:%SZ)\" > /tmp/mlcc-result.json\n"
        f"  aws s3 cp --only-show-errors /tmp/mlcc-result.json '{dest}{RESULT_FILE}' || up=1\n"
        "fi\n"
        "if [ \"$up\" = 0 ] && [ \"$rc\" = 0 ]; then\n"
        f"{clear}"
        "  echo 'MLCC egress: done'\n"
        "else\n"
        f"  echo 'MLCC egress: upload error or failed workload; scratch kept at {SCRATCH}'\n"
        "fi\n"
        f"touch {SCRATCH}/.mlcc-egress-done\n"
        "while :; do sleep 3600; done\n")
    return {"name": "mlcc-egress", "image": AWS_CLI_IMAGE, "command": ["/bin/sh", "-c", script],
            "env": _region_env(region), "volumeMounts": [dict(mount)]}


def wrap_main_command(workload: str) -> list[str]:
    """The main container's `sh -c` wrapper (design §4). `workload` is the shell
    command that runs training; its output is tee'd to the durable per-job log."""
    script = (
        "set -u\n"
        f"if [ -f {SCRATCH}/.mlcc-exit ]; then\n"
        f"  echo \"MLCC: workload already finished (exit $(cat {SCRATCH}/.mlcc-exit)); waiting for the watcher\"\n"
        "  while :; do sleep 3600; done\n"
        "fi\n"
        f"mkdir -p {SCRATCH}/logs {SCRATCH}/output {SCRATCH}/checkpoints\n"
        "if ! command -v hyperpodrun >/dev/null 2>&1; then\n"
        "  echo 'MLCC_PRECONDITION hyperpodrun-missing: the training image has no hyperpodrun "
        "(HyperPodPyTorchJob needs it: pip install hyperpod-elastic-agent in TRAIN_IMAGE)' "
        f"| tee -a {SCRATCH}/logs/train.log\n"
        f"  echo 3 > {SCRATCH}/.mlcc-exit\n"
        "  while :; do sleep 3600; done\n"
        "fi\n"
        f"( {workload}; echo $? > {SCRATCH}/.mlcc-rc ) 2>&1 | tee -a {SCRATCH}/logs/train.log\n"
        f"cat {SCRATCH}/.mlcc-rc 2>/dev/null > {SCRATCH}/.mlcc-exit || echo 1 > {SCRATCH}/.mlcc-exit\n"
        f"echo \"MLCC: workload exit $(cat {SCRATCH}/.mlcc-exit)\"\n"
        "while :; do sleep 3600; done\n")
    return ["/bin/sh", "-c", script]


def _region_env(region: str) -> list[dict]:
    return [{"name": "AWS_REGION", "value": region}, {"name": "AWS_DEFAULT_REGION", "value": region}] if region else []


def run_policy(max_runtime: int) -> dict:
    # jobMaxRetryCount 0: an in-process failure goes Failed in ~1 s (F0 attempt 2).
    # cleanPodPolicy None: the operator must not remove the pod before the egress
    # container has uploaded (the watcher deletes the HPPJ itself). Both fields
    # are in the live CRD schema (Task 1 `kubectl explain`); F0 applied both.
    return {"jobMaxRetryCount": 0, "cleanPodPolicy": "None", "activeDeadlineSeconds": int(max_runtime)}


# ── render-train (R4) ──────────────────────────────────────────────────────────


def plugin_configmap(name: str, namespace: str, plugin_dir: str, lbl: dict) -> dict:
    """R4.3: the plugin directory (flat) + the generated launcher in one ConfigMap;
    refused above 1 MiB (the API server's object limit)."""
    if not os.path.isdir(plugin_dir):
        raise RenderError(f"plugin directory not found: {plugin_dir}")
    data = {"launch.py": LAUNCH_PY}
    for entry in sorted(os.listdir(plugin_dir)):
        path = os.path.join(plugin_dir, entry)
        if entry.startswith(".") or entry == "__pycache__":
            continue
        if os.path.isdir(path):
            raise RenderError(f"plugin subdirectory '{entry}' cannot ship in a ConfigMap (keys are flat); "
                              "flatten it or bake it into TRAIN_IMAGE")
        try:
            with open(path, encoding="utf-8") as fh:
                data[entry] = fh.read()
        except UnicodeDecodeError:
            raise RenderError(f"plugin file '{entry}' is not UTF-8 text; bake binaries into TRAIN_IMAGE") from None
    if "train.py" not in data:
        raise RenderError(f"{plugin_dir} has no train.py")
    size = sum(len(k.encode()) + len(v.encode()) for k, v in data.items())
    if size > CONFIGMAP_MAX_BYTES:
        raise RenderError(f"the plugin ConfigMap would be {size} bytes (> 1 MiB limit); "
                          "move large files into TRAIN_IMAGE or the dataset")
    return {"apiVersion": "v1", "kind": "ConfigMap",
            "metadata": {"name": name, "namespace": namespace, "labels": dict(lbl)}, "data": data}


def render_train(a: dict) -> list[dict]:
    project, job, ns, kind = a["project"], a["job"], a["namespace"], "train"
    lbl = labels(project, kind, a.get("technique") or "custom", job)
    gpus = int(a["gpus"])
    if gpus < 1:
        raise UsageError("--gpus must be >= 1")
    cm_name = f"{job}-plugin"
    cm = plugin_configmap(cm_name, ns, a["plugin_dir"], lbl)
    size_gib = None
    if a["scratch"] == "ephemeral":
        size_gib = scratch_gib(a.get("model_bytes"), a.get("scratch_size") or "")
    vol, mount = scratch_volume(a["scratch"], project, job, size_gib, a.get("storage_class") or "", lbl)
    dataset = a.get("dataset") or ""
    volumes = [vol, {"name": "mlcc-plugin", "configMap": {"name": cm_name}},
               {"name": "shm", "emptyDir": {"medium": "Memory"}}]
    mounts = [dict(mount), {"name": "mlcc-plugin", "mountPath": PLUGIN_MOUNT, "readOnly": True},
              {"name": "shm", "mountPath": "/dev/shm"}]
    data_dir = f"{SCRATCH}/data"
    if dataset.startswith("fsx://"):
        sub = dataset[len("fsx://"):].strip("/")
        if not sub or ".." in sub.split("/"):
            raise UsageError(f"--dataset {dataset}: an fsx:// subpath without '..' is required")
        volumes.append({"name": "mlcc-dataset", "persistentVolumeClaim": {"claimName": FSX_CLAIM, "readOnly": True}})
        mounts.append({"name": "mlcc-dataset", "mountPath": "/mlcc-data", "subPath": sub, "readOnly": True})
        data_dir = "/mlcc-data"
    model_uri = a.get("model_uri") or ""
    hf_model = f"{SCRATCH}/model" if model_uri.startswith("s3://") else (a.get("hf_model_id") or "")
    env = [{"name": k, "value": str(v)} for k, v in sorted((a.get("env") or {}).items())]
    env += [
        {"name": "DATA_DIR", "value": data_dir},
        {"name": "OUTPUT_DIR", "value": f"{SCRATCH}/output"},
        {"name": "CHECKPOINT_DIR", "value": f"{SCRATCH}/checkpoints"},
        {"name": "HF_MODEL_ID", "value": hf_model},
        {"name": "NUM_GPUS", "value": str(gpus)},
        {"name": "SM_HPS", "value": json.dumps(a.get("hparams") or {})},
        {"name": "MLCC_LAUNCHER", "value": a.get("launcher") or "accelerate"},
        {"name": "MLCC_JOB_NAME", "value": job},
        {"name": "HF_TOKEN", "valueFrom": {"secretKeyRef": {"name": "hf-token-secret", "key": "token", "optional": True}}},
    ] + _region_env(a.get("region") or "")
    workload = f"hyperpodrun --nnodes=1 --nproc-per-node=1 {PLUGIN_MOUNT}/launch.py"
    main = {"name": "mlcc-train", "image": a["image"], "command": wrap_main_command(workload),
            "env": env, "volumeMounts": mounts,
            # One whole node's GPUs (or --gpus); single node, so no EFA request.
            "resources": {"requests": {"nvidia.com/gpu": gpus}, "limits": {"nvidia.com/gpu": gpus}}}
    dest = output_prefix(a["artifacts_bucket"], project, kind, job)
    pod = {"serviceAccountName": SERVICE_ACCOUNT,
           "nodeSelector": {GROUP_LABEL: a["group"]},
           "initContainers": [fetch_container(dataset, model_uri, a.get("region") or "", mount)],
           "containers": [main, egress_container(dest, job, a.get("region") or "", mount, a["scratch"] == "fsx")],
           "volumes": volumes}
    hppj = {"apiVersion": HPPJ_API, "kind": HPPJ_KIND,
            "metadata": {"name": job, "namespace": ns, "labels": dict(lbl)},
            "spec": {"nprocPerNode": "1",
                     "runPolicy": run_policy(a["max_runtime"]),
                     "replicaSpecs": [{"name": "1-nodes", "replicas": 1,
                                       "template": {"metadata": {"labels": dict(lbl)}, "spec": pod}}]}}
    return [cm, hppj]


# ── classify (R6) ──────────────────────────────────────────────────────────────


def _container_statuses(pod: dict) -> list[dict]:
    st = pod.get("status") or {}
    return list(st.get("initContainerStatuses") or []) + list(st.get("containerStatuses") or [])


def _terminated_exit(cs: dict) -> int | None:
    for key in ("state", "lastState"):
        term = (cs.get(key) or {}).get("terminated")
        if term and term.get("exitCode") is not None:
            return int(term["exitCode"])
    return None


def classify(hppj: dict | None, pods: list[dict], result: dict | None, now: float, t0: float,
             last_log_age: float | None, limits: dict) -> tuple[str, str]:
    """Pure: map one observation to (state, reason). state ∈ Succeeded | Failed |
    Running | Pending. Success is ONLY a _MLCC_RESULT.json with exit 0 and output
    (R6.1), never a condition name."""
    main = limits.get("main", "mlcc-train")
    if result is not None:
        code = result.get("exit_code")
        if code == 0 and int(result.get("files") or 0) > 0:
            return "Succeeded", f"_MLCC_RESULT.json: exit 0, {result.get('files')} file(s)"
        if code == 0:
            return "Failed", "_MLCC_RESULT.json: exit 0 but the job wrote no output"
        if code == 3:
            return "Failed", "precondition: the workload never started (see MLCC_PRECONDITION in the logs)"
        return "Failed", f"_MLCC_RESULT.json: workload exit {code}"
    for cond in ((hppj or {}).get("status") or {}).get("conditions") or []:
        if cond.get("type") == "Failed" and cond.get("status") == "True":
            return "Failed", f"HyperPodPyTorchJob Failed: {cond.get('reason') or ''} {cond.get('message') or ''}".strip()
    running = False
    for p in pods:
        st = p.get("status") or {}
        if st.get("phase") == "Failed":
            return "Failed", f"pod {p['metadata']['name']} {st.get('reason') or 'Failed'}: {st.get('message') or ''}".strip()
        for cs in _container_statuses(p):
            if int(cs.get("restartCount") or 0) >= 2:
                return "Failed", f"container {cs.get('name')} restarted {cs.get('restartCount')}x (crash loop)"
            if cs.get("name") == main:
                code = _terminated_exit(cs)
                if code not in (None, 0):
                    return "Failed", f"main container {main} exited {code}"
                if "running" in (cs.get("state") or {}):
                    running = True
    elapsed = now - t0
    deadline = limits.get("deadline") or 0
    if deadline and elapsed > deadline:
        return "Failed", f"deadline: activeDeadlineSeconds {deadline} exceeded"
    if not running:
        startup = limits.get("startup", DEFAULT_STARTUP_TIMEOUT)
        if startup and elapsed > startup:
            return "Failed", f"startup: not Running within --startup-timeout {startup}s"
        return "Pending", "waiting for the pod to start"
    stall = limits.get("stall", DEFAULT_STALL_TIMEOUT)
    if stall and last_log_age is not None and last_log_age > stall:
        return "Failed", (f"stalled: no new log line for {int(last_log_age)}s (> --stall-timeout {stall}); "
                          "a silent rank hang looks like this (py-spy dump the main process to see where)")
    return "Running", "workload running"


