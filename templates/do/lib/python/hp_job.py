"""hp_job.py — the shared single-node HyperPodPyTorchJob substrate (Wave 11 R4–R6).

`do/train --backend hp-eks` renders its own HPPJ around the user plugin
(render-train); `do/tune --backend hp-eks` patches AWS's Hub payload and applies
the SAME pod additions (pod_additions, used by hp_payload.py). Both are watched by
the same classifier, which maps the HPPJ status quirks seen in the F0 probe to
terminal states and ALWAYS deletes the HPPJ on a terminal state (a terminal
`Failed` HPPJ's Deployment re-creates the pod and holds the GPUs otherwise).

stdlib only; every cluster / cloud call goes through the `kubectl` and `aws` CLIs
(stubbed on PATH / via _run in tests). MLCC's only cluster writes here are its own
ServiceAccount (mlcc-train-sa), the per-job ConfigMap and the HPPJ, all labeled
mlcc.aws/project-name=<project> (ADR-012).

Pod additions (shared by train and tune):
  * scratch volume `mlcc-scratch` at /scratch — the fsx-claim subpath
    mlcc/<project>/<job>/ when Bound, else a generic ephemeral volume on the
    cluster's StorageClass sized max(50 GiB, ceil(2.5 x base-model bytes)) or
    --scratch-size. Output never lands on the container overlay (F0 eviction).
  * init container `mlcc-fetch` (pinned AWS CLI image): dataset → /scratch/data,
    staged model → /scratch/model (Pod Identity credentials reach every container).
  * the main container's command is wrapped: a missing `hyperpodrun` prints
    `MLCC_PRECONDITION hyperpodrun-missing` and records exit 3 in seconds; the
    workload is tee'd to /scratch/logs/train.log and its exit code written to
    /scratch/.mlcc-exit. The wrapper then idles (never re-runs the workload on a
    container restart) until the watcher deletes the HPPJ.
  * egress container `mlcc-egress` (same image): waits for .mlcc-exit, uploads
    logs/ always and output/ only on exit 0 to s3://<artifacts>/<project>/<kind>/
    <job>/, writes _MLCC_RESULT.json LAST, and on success clears its own fsx
    subpath.

Subcommands (JSON on stdout, human notes on stderr):
  render-train --project P --job J --namespace N --image I --group G --gpus N
               --technique T --plugin-dir D --dataset URI --artifacts-bucket B
               --region R --max-runtime S [--model-uri s3://...] [--hf-model-id ID]
               [--scratch fsx|ephemeral --storage-class SC --scratch-size NGi]
               [--env-json {...}] [--hparams-json {...}] [--launcher accelerate|python]
               --out FILE
  scratch-size --model-uri s3://... [--scratch-size NGi]
  submit --manifest FILE --namespace N
  watch|status --job J --namespace N --artifacts-bucket B --project P --kind train|tune
               [--main-container C] [--startup-timeout S] [--stall-timeout S]
               [--deadline S] [--poll S]
  stop --job J --namespace N
  logs --job J --namespace N [--main-container C]
Exit codes: 0 ok / Succeeded; 2 failed terminal state, delete error, or bad input
(usage); 3 render refusal (ConfigMap > 1 MiB, unreadable plugin, no scratch size).
"""

