def _kubectl_json(args: list[str]) -> dict | None:
    rc, out, _ = _run(["kubectl", *args, "-o", "json"])
    data = _json(out) if rc == 0 else None
    return data if isinstance(data, dict) else None


def observe(job: str, ns: str, dest: str) -> tuple[dict | None, list[dict], dict | None, bool]:
    """One read-only observation: (hppj, pods, result, hppj_exists)."""
    rc, out, err = _run(["kubectl", "get", "hyperpodpytorchjob", job, "-n", ns, "-o", "json"])
    exists = rc == 0
    hppj = _json(out) if exists else None
    pods = (_kubectl_json(["get", "pods", "-n", ns, "-l", f"{LABEL_JOB}={job}"]) or {}).get("items") or []
    rc, out, _ = _aws(["s3", "cp", f"{dest}{RESULT_FILE}", "-"])
    result = _json(out) if rc == 0 else None
    return hppj, pods, (result if isinstance(result, dict) else None), exists


def delete_job(job: str, ns: str, wait: int = 120) -> tuple[int, str]:
    """Delete the HPPJ (releasing its Deployment's GPUs) and its plugin ConfigMap,
    then wait up to `wait` s for the pods to go. A failed delete prints the manual
    command (exit 2)."""
    cmd = ["kubectl", "delete", "hyperpodpytorchjob", job, "-n", ns, "--wait=false", "--ignore-not-found"]
    rc, _, err = _run(cmd)
    if rc != 0:
        return 2, f"could not delete the HyperPodPyTorchJob: {err.strip()[:300]}\n   Run: {' '.join(cmd)}"
    _run(["kubectl", "delete", "configmap", f"{job}-plugin", "-n", ns, "--ignore-not-found"])
    deadline = time.time() + wait
    while time.time() < deadline:
        pods = (_kubectl_json(["get", "pods", "-n", ns, "-l", f"{LABEL_JOB}={job}"]) or {"items": None}).get("items")
        if pods == []:
            return 0, "HyperPodPyTorchJob deleted; pods gone (GPUs released)"
        time.sleep(5)
    return 0, "HyperPodPyTorchJob deleted; pods still terminating (they release the GPUs as they exit)"


def tail_logs(job: str, ns: str, main: str, previous: bool = False) -> str:
    args = ["kubectl", "logs", "-n", ns, "-l", f"{LABEL_JOB}={job}", "-c", main, "--tail=200"]
    if previous:
        args.append("--previous")
    rc, out, err = _run(args)
    text = out if rc == 0 else err
    if "mlcc-fetch" not in text:
        rc2, out2, _ = _run(["kubectl", "logs", "-n", ns, "-l", f"{LABEL_JOB}={job}", "-c", "mlcc-fetch", "--tail=50"])
        if rc2 == 0 and out2.strip():
            text = out2 + "\n" + text
    return text


def _recent_log(job: str, ns: str, main: str, window: int) -> bool:
    rc, out, _ = _run(["kubectl", "logs", "-n", ns, "-l", f"{LABEL_JOB}={job}", "-c", main,
                       f"--since={max(1, window)}s", "--tail=1"])
    return rc == 0 and bool(out.strip())


def _terminal(state: str, reason: str, job: str, ns: str, dest: str, main: str) -> tuple[int, dict]:
    out = {"state": state, "reason": reason, "job": job, "artifact_prefix": f"{dest}output",
           "logs_uri": f"{dest}logs/train.log"}
    if state != "Succeeded":
        logs = tail_logs(job, ns, main, previous=reason.startswith(("startup", "container")))
        print("── last 200 log lines ──", file=sys.stderr)
        print(logs.rstrip(), file=sys.stderr)
        for line in logs.splitlines():
            if "MLCC_PRECONDITION" in line:
                out["precondition"] = line.strip()
    rc, msg = delete_job(job, ns)
    out["delete"] = msg
    _note(f"   {msg}")
    if rc != 0:
        return 2, out
    return (0 if state == "Succeeded" else 2), out


def watch(a: dict, once: bool = False) -> tuple[int, dict]:
    job, ns, main = a["job"], a["namespace"], a.get("main") or "mlcc-train"
    dest = output_prefix(a["artifacts_bucket"], a["project"], a["kind"], job)
    limits = {"main": main, "startup": a["startup"], "stall": a["stall"], "deadline": a["deadline"]}
    t0 = a.get("t0") or time.time()
    last_seen = None
    poll = max(1, int(a.get("poll") or 60))
    while True:
        hppj, pods, result, exists = observe(job, ns, dest)
        now = time.time()
        if hppj is not None:
            created = ((hppj.get("metadata") or {}).get("creationTimestamp") or "")
            ts = _parse_ts(created)
            if ts and not a.get("t0"):
                t0 = ts
        if not exists and result is None:
            return 2, {"state": "Unknown", "reason": f"HyperPodPyTorchJob {ns}/{job} not found and no {RESULT_FILE}",
                       "job": job}
        if not exists and result is not None:
            state, reason = classify(None, [], result, now, t0, None, limits)
            return (0 if state == "Succeeded" else 2), {"state": state, "reason": reason, "job": job,
                                                         "artifact_prefix": f"{dest}output"}
        if _recent_log(job, ns, main, poll * 2) or last_seen is None:
            last_seen = now
        state, reason = classify(hppj, pods, result, now, t0, now - last_seen, limits)
        if state in ("Succeeded", "Failed"):
            return _terminal(state, reason, job, ns, dest, main)
        print(f"   🔄 {state}: {reason}", file=sys.stderr)
        if once:
            return 0, {"state": state, "reason": reason, "job": job}
        time.sleep(poll)


def _parse_ts(value: str) -> float | None:
    try:
        return float(calendar.timegm(time.strptime(value, "%Y-%m-%dT%H:%M:%SZ")))
    except (ValueError, TypeError):
        return None


def submit(manifest: str, ns: str) -> tuple[int, str]:
    rc, sa_yaml, err = _run(["kubectl", "create", "serviceaccount", SERVICE_ACCOUNT, "-n", ns,
                             "--dry-run=client", "-o", "yaml"])
    if rc != 0:
        return 1, f"could not render the ServiceAccount: {err.strip()}"
    rc, _, err = _run(["kubectl", "apply", "-f", "-"], stdin=sa_yaml)
    if rc != 0:
        return 1, f"could not create ServiceAccount {ns}/{SERVICE_ACCOUNT}: {err.strip()}"
    rc, out, err = _run(["kubectl", "apply", "-f", manifest])
    if rc != 0:
        return 1, err.strip() or out.strip()
    return 0, out.strip()


