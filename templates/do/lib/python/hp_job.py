"""MLCC hp-eks launcher (generated by hp_job.py): runs under hyperpodrun with one
worker, clears the torchrun / elastic env, then launches the plugin exactly as on
SMTJ (accelerate launch --num_processes $NUM_GPUS train.py) and returns its exit."""
