def _cli(argv: list[str]) -> int:
    p = argparse.ArgumentParser(prog="hp_job.py")
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("render-train")
    for flag in ("--project", "--job", "--namespace", "--image", "--group", "--technique", "--plugin-dir",
                 "--artifacts-bucket", "--out"):
        r.add_argument(flag, required=True)
    r.add_argument("--gpus", type=int, required=True)
    r.add_argument("--max-runtime", type=int, required=True)
    r.add_argument("--dataset", default="")
    r.add_argument("--region", default=os.environ.get("AWS_REGION", ""))
    r.add_argument("--model-uri", default="")
    r.add_argument("--hf-model-id", default="")
    r.add_argument("--scratch", default="fsx", choices=["fsx", "ephemeral"])
    r.add_argument("--storage-class", default="")
    r.add_argument("--scratch-size", default="")
    r.add_argument("--env-json", default="{}")
    r.add_argument("--hparams-json", default="{}")
    r.add_argument("--launcher", default="accelerate")
    s = sub.add_parser("scratch-size")
    s.add_argument("--model-uri", default="")
    s.add_argument("--scratch-size", default="")
    m = sub.add_parser("submit")
    m.add_argument("--manifest", required=True)
    m.add_argument("--namespace", required=True)
    for name in ("watch", "status"):
        w = sub.add_parser(name)
        w.add_argument("--job", required=True)
        w.add_argument("--namespace", required=True)
        w.add_argument("--artifacts-bucket", required=True)
        w.add_argument("--project", required=True)
        w.add_argument("--kind", default="train", choices=["train", "tune"])
        w.add_argument("--main-container", default="mlcc-train")
        w.add_argument("--startup-timeout", default=str(DEFAULT_STARTUP_TIMEOUT))
        w.add_argument("--stall-timeout", default=str(DEFAULT_STALL_TIMEOUT))
        w.add_argument("--deadline", default="0")
        w.add_argument("--poll", default="60")
    for name in ("stop", "logs"):
        x = sub.add_parser(name)
        x.add_argument("--job", required=True)
        x.add_argument("--namespace", required=True)
        x.add_argument("--main-container", default="mlcc-train")
    args = p.parse_args(argv)
    try:
        if args.cmd == "render-train":
            env, hps = _json(args.env_json), _json(args.hparams_json)
            if not isinstance(env, dict) or not isinstance(hps, dict):
                raise UsageError("--env-json / --hparams-json must be JSON objects")
            model_bytes = s3_prefix_bytes(args.model_uri) if (args.scratch == "ephemeral" and args.model_uri
                                                              and not args.scratch_size) else None
            docs = render_train({
                "project": args.project, "job": args.job, "namespace": args.namespace, "image": args.image,
                "group": args.group, "gpus": args.gpus, "technique": args.technique, "plugin_dir": args.plugin_dir,
                "dataset": args.dataset, "model_uri": args.model_uri, "hf_model_id": args.hf_model_id,
                "artifacts_bucket": args.artifacts_bucket, "region": args.region, "max_runtime": args.max_runtime,
                "scratch": args.scratch, "storage_class": args.storage_class, "scratch_size": args.scratch_size,
                "model_bytes": model_bytes, "env": env, "hparams": hps, "launcher": args.launcher})
            with open(args.out, "w", encoding="utf-8") as fh:
                json.dump({"apiVersion": "v1", "kind": "List", "items": docs}, fh, indent=2)
            print(json.dumps({"manifest": args.out, "configmap": docs[0]["metadata"]["name"],
                              "job": args.job, "group": args.group, "gpus": args.gpus,
                              "output_prefix": output_prefix(args.artifacts_bucket, args.project, "train", args.job)}))
            return 0
        if args.cmd == "scratch-size":
            size = scratch_gib(s3_prefix_bytes(args.model_uri) if args.model_uri else None, args.scratch_size)
            print(json.dumps({"scratch_gib": size}))
            return 0
        if args.cmd == "submit":
            rc, msg = submit(args.manifest, args.namespace)
            print(json.dumps({"applied": rc == 0, "message": msg}))
            return rc
        if args.cmd in ("watch", "status"):
            a = {"job": args.job, "namespace": args.namespace, "artifacts_bucket": args.artifacts_bucket,
                 "project": args.project, "kind": args.kind, "main": args.main_container,
                 "startup": validate_timeout("--startup-timeout", args.startup_timeout),
                 "stall": validate_timeout("--stall-timeout", args.stall_timeout),
                 "deadline": validate_timeout("--deadline", args.deadline),
                 "poll": validate_timeout("--poll", args.poll)}
            try:
                rc, out = watch(a, once=args.cmd == "status")
            except KeyboardInterrupt:
                _note("\n⚠  Detached — the HyperPodPyTorchJob keeps running. Re-attach / clean up with --status.")
                return 130
            print(json.dumps(out))
            return rc
        if args.cmd == "stop":
            rc, msg = delete_job(args.job, args.namespace)
            print(json.dumps({"stopped": rc == 0, "message": msg}))
            return rc
        print(tail_logs(args.job, args.namespace, args.main_container))
        return 0
    except UsageError as exc:
        _note(f"❌ {exc}")
        return 2
    except RenderError as exc:
        _note(f"❌ {exc}")
        return 3


if __name__ == "__main__":
    sys.exit(_cli(sys.argv[1:]))
